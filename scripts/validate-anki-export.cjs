/* eslint-disable @typescript-eslint/no-require-imports -- Validate source without a production build. */
const fs = require("node:fs");
const path = require("node:path");
const Module = require("node:module");
const ts = require("typescript");
const assert = require("node:assert/strict");
const original = Module._resolveFilename;
Module._resolveFilename = function(request, ...args) { return original.call(this, request.startsWith("@/") ? path.resolve(__dirname, "..", request.slice(2)) : request, ...args); };
require.extensions[".ts"] = require.extensions[".tsx"] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, jsx: ts.JsxEmit.ReactJSX } }).outputText, filename);
const { prepareAnkiText, ankiExportFilename } = require("../lib/anki-export.ts");
const raw = "利く\tได้ผล\t\tShinkanzen\t\r\n社交的\tเข้าสังคมเก่ง\t\tShinkanzen\t\r\n";
const parsed = prepareAnkiText(raw);
assert.equal(parsed.columns, 5);
assert.equal(parsed.count, 2);
assert.deepEqual(parsed.errors, []);
assert.equal(parsed.text, raw.replace(/\r\n/g, "\n"), "Preserve trailing empty fields and Japanese");
assert.equal(prepareAnkiText("คำ\tความหมาย\t").columns, 3);
assert.ok(prepareAnkiText("คำ\tแปล\nคำ\tแปล\tแท็ก").errors.length);
assert.ok(prepareAnkiText("| คำ | แปล |").errors.length);
assert.ok(prepareAnkiText("").errors.length);
const fenced = "```tsv\n利く\tได้ผล\t\n```";
assert.equal(prepareAnkiText(fenced).text, "利く\tได้ผล\t\n");
assert.equal(prepareAnkiText("#separator:Tab\n利く\tได้ผล").count, 1);
assert.equal(ankiExportFilename("N1.tsv", "txt"), "N1.txt");
assert.equal(ankiExportFilename("../N1", "tsv"), "..-N1.tsv");
assert.equal(ankiExportFilename("", "txt"), "Shinkanzen.txt");
const React = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const component = require("../app/anki-export.tsx").default;
const html = renderToStaticMarkup(React.createElement(component));
assert.ok(html.includes('id="anki-export-text"'));
assert.ok(html.includes("ดาวน์โหลด Shinkanzen.txt"));
assert.ok(html.includes('disabled=""'), "Cannot download an empty file");
const app = fs.readFileSync(path.resolve(__dirname, "../app/oboeru-app.tsx"), "utf8");
assert.ok(app.includes('label: "สร้างไฟล์ Anki"'));
assert.ok(!app.includes('id: "examples", label:'));
assert.ok(!app.includes('{section === "examples" ?'));
assert.ok(app.includes('stored.lastSection === "examples" ? "vocabulary"'));
console.log("Anki TSV preservation, column checks, filenames, empty UI and removed examples navigation passed.");
